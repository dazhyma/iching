/* Тип вопроса: о чём человек спрашивает на самом деле.
   Одно и то же «что будет с бизнесом» и «стоит ли открывать бизнес» —
   разные вопросы, и ответ должен начинаться по-разному.

   Возвращает { id, direct } где direct — прямой ответ на да/нет,
   собранный позже из профиля темы. */

(function (root) {
  /* Порядок проверок важен: более узкие типы идут раньше. */
  const RULES = [
    /* «Почему не получается?» — человек ищет причину, а не прогноз. */
    { id: "why", re: /(^|[^а-я])(почему|отчего|из за чего|причина|причин[уые]|что мешает|в чем дело)([^а-я]|$)/ },

    /* «Когда это случится?» — вопрос о сроке. */
    { id: "timing", re: /(^|[^а-я])(когда|через сколько|как скоро|сколько ждать|какого числа|в каком месяце|к какому сроку|скоро ли)([^а-я]|$)/ },

    /* «Что мне делать?» — человек просит действие. */
    { id: "how", re: /(^|[^а-я])(как мне|что мне делать|что делать|как поступить|как быть|что поможет|как наладить|как сохранить|как добиться|что нужно|как лучше|как правильно)([^а-я]|$)/ },

    /* «Менять или нет?», «A или B?» — выбор между вариантами. */
    { id: "choice", re: /(^|[^а-я])(или|выбрать|выбор|стоит ли выбрать|что лучше)([^а-я]|$)/ }
  ];

  /* Вопрос «да/нет»: частица «ли» рядом со сказуемым, либо типичный зачин. */
  const YESNO = /(^|[^а-я])(ли)([^а-я]|$)/;
  const YESNO_LEAD = /^(будет|будут|получится|получу|смогу|выйдет|верн[её]тся|вернется|стоит|удастся|принес[её]т|хватит|успею|найду|выиграю|сдам|поступлю|получу|дадут|даст)/;

  /* «Что будет / что ждёт» — вопрос о ходе событий. */
  const OUTCOME = /(^|[^а-я])(что будет|что жд[её]т|что ждет|чем закончится|чем кончится|как сложится|как будет|что ожидать)([^а-я]|$)/;

  function detect(text) {
    const t = String(text || "").toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
    if (!t) return { id: "outcome" };

    for (const r of RULES) {
      /* «или» само по себе слишком частое: для выбора нужен ещё признак вопроса */
      if (r.id === "choice") {
        const twoOptions = /(^|[^а-я])или([^а-я]|$)/.test(t) && t.length > 15;
        if (twoOptions || /выбр/.test(t)) return { id: "choice" };
        continue;
      }
      if (r.re.test(t)) return { id: r.id };
    }

    if (YESNO.test(t) || YESNO_LEAD.test(t)) return { id: "yesno" };
    if (OUTCOME.test(t)) return { id: "outcome" };
    return { id: "outcome" };
  }

  const api = { detect };
  if (typeof module !== "undefined") module.exports = api; else root.Intent = api;
})(typeof window !== "undefined" ? window : globalThis);
