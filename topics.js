  function normalize(text) {
    return String(text || "")
      .toLowerCase()
      .replace(/ё/g, "е")
      .replace(/[^a-zа-я0-9\s-]/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  }

  function tokens(norm) { return norm ? norm.split(" ") : []; }

  function classify(rawText) {
    const raw = String(rawText || "");
    const norm = normalize(raw);
    const toks = tokens(norm);
    const scores = { family: 0, health: 0, love: 0, work: 0, money: 0, study: 0,
                     home: 0, move: 0, legal: 0, loss: 0, act: 0 };
    const found = {};
    for (const k in scores) found[k] = [];

    if (!toks.length) return { id: "general", scores, found };

    for (const cat in KEYWORDS) {
      const groups = KEYWORDS[cat];
      for (const weight of [3, 2, 1]) {
        const g = groups[weight];
        if (!g) continue;

        for (const stem of g.start || []) {
          for (const tok of toks) {
            if (BLOCK.has(tok)) continue;
            if (tok.startsWith(stem)) {
              scores[cat] += weight;
              found[cat].push(stem + "(" + weight + ")");
              break;
            }
          }
        }
        for (const ex of g.exact || []) {
          if (toks.includes(ex)) {
            // не дублируем, если эта же тема уже засчитана по основе
            const already = (found[cat] || []).length > 0 &&
              (g.start || []).some(st => ex.startsWith(st));
            if (!already) { scores[cat] += weight; found[cat].push(ex + "=(" + weight + ")"); }
          }
        }
      }
    }

    /* ── приоритетные маркеры ── */
    for (const [cat, re] of PRIORITY) {
      if (re.test(norm)) return { id: cat, scores, found, forced: true };
    }

    /* ── выбор темы ── */
    let best = null, bestScore = 0;
    for (const cat of CONCRETE) {
      if (scores[cat] > bestScore) { bestScore = scores[cat]; best = cat; }
    }

    if (best) {
      // «Стоит ли менять работу»: сомнение не отменяет конкретную тему,
      // но если конкретика совсем слабая, а сомнение сильное — берём act.
      if (scores.act > 0 && bestScore <= 1 && scores.act >= 3) {
        return { id: "act", scores, found };
      }
      return { id: best, scores, found };
    }

    if (scores.act > 0) return { id: "act", scores, found };
    if (FUTURE_RE.test(norm)) return { id: "future", scores, found };
    return { id: "general", scores, found };
  }

