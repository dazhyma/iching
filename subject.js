/* Извлечение предмета вопроса: о ком или о чём спрашивают.
   Нужно, чтобы ответ говорил не «о периоде вообще», а о детях,
   о бизнесе, о здоровье — о том, что человек назвал сам.

   Возвращает { key, phrase } где phrase уже в правильной форме
   («ваших детей», «ваш бизнес»), либо null. */

(function (root) {
  /* Формы заданы вручную: склонять русские существительные программно
     — источник ошибок («ваших бизнесов»). Таблица надёжнее. */
  const SUBJECTS = [
    { key: "children", phrase: "ваших детей",
      re: /(^|[^а-я])(дети|детей|детям|детьми|детях|ребен|ребён|сын|сына|сыну|сыном|дочер|дочк|дочка|дочке|дочку)/i },

    { key: "family", phrase: "вашу семью",
      re: /(^|[^а-я])(семья|семьи|семье|семью|семьей|семьёй|семейн|родител|мама|маме|маму|мамой|мать|папа|папе|папу|папой|отец|отца|отцу|отцом|брат|брата|брату|сестр|сестра|сестре|бабушк|дедушк)/i },

    { key: "business", phrase: "ваш бизнес",
      re: /(^|[^а-я])(бизнес|фирм|компани|магазин|предприят|дело|дела|проект)/i },

    { key: "money", phrase: "ваши деньги",
      re: /(^|[^а-я])(деньг|денег|доход|прибыл|зарплат|финанс|накоплен|сбережен)/i },

    { key: "work", phrase: "вашу работу",
      re: /(^|[^а-я])(работа|работу|работе|работы|работой|карьер|должност|служб)/i },

    { key: "love", phrase: "ваши отношения",
      re: /(^|[^а-я])(отношен|любов|любим|брак|муж|жена|партнер|партнёр|парень|девушк|невест|жених)/i },

    { key: "health", phrase: "ваше здоровье",
      re: /(^|[^а-я])(здоров|болезн|самочувств|лечени|операци|диагноз)/i },

    { key: "study", phrase: "вашу учёбу",
      re: /(^|[^а-я])(учеб|учёб|учеба|учёба|экзамен|егэ|огэ|сесси|диплом|институт|универ|вуз|колледж|поступ)/i },

    { key: "home", phrase: "ваше жильё",
      re: /(^|[^а-я])(квартир|жилье|жильё|дом|дома|дому|ремонт|недвижим|аренд|участок|дач)/i },

    { key: "move", phrase: "переезд",
      re: /(^|[^а-я])(переезд|перееха|эмиграц|виза|визу|релокац|поездк|командировк|отпуск)/i },

    { key: "legal", phrase: "ваше дело",
      re: /(^|[^а-я])(суд|суда|суде|суду|иск|иска|иске|наследств|договор|адвокат)/i },

    { key: "loss", phrase: "пропажу",
      re: /(^|[^а-я])(пропал|пропаж|потерял|потеря|украл|украд|краж|исчез)/i }
  ];

  /* Возвращает предмет вопроса или null, если ничего не нашли. */
  function extract(text) {
    const t = String(text || "").toLowerCase().replace(/ё/g, "е");
    if (!t.trim()) return null;
    for (const s of SUBJECTS) {
      const re = new RegExp(s.re.source.replace(/ё/g, "е"), "i");
      if (re.test(t)) return { key: s.key, phrase: s.phrase };
    }
    return null;
  }

  const api = { extract, SUBJECTS };
  if (typeof module !== "undefined") module.exports = api; else root.Subject = api;
})(typeof window !== "undefined" ? window : globalThis);
