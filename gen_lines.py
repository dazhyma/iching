PREFIX = ["", "На практике: ", "Если посмотреть прямо: ", "По сути: "]


def split_sentences(text: str):
    text = text.replace("—", " — ")
    parts = re.split(r"(?<=[.!?])\s+", text.strip())
    out = []
    for p in parts:
        p = p.strip()
        if len(p) < 8:
            continue
        p = re.sub(r"\s+—\s+", " — ", p)
        out.append(p if p[-1] in ".!?" else p + ".")
    return out


def pool_for(h):
    """Содержательные фразы гексаграммы: ситуация и совет.
    Образ (поле e) — назывная фраза, посреди предложения читается обрубком,
    поэтому в «тело» линии он не идёт, только в зачин через IMAGE."""
    raw = split_sentences(h["t"]) + split_sentences(h["a"])
    seen, uniq = set(), []
    for s in raw:
        key = s.lower()[:40]
        if key not in seen:
            seen.add(key)
            uniq.append(s)
    # добиваем производными, чтобы на шесть линий хватило различий
    extra = []
    for s in uniq[:3]:
        low = s[0].lower() + s[1:] if s else s
        for pre in PREFIX[1:]:
            extra.append(pre + low)
    for s in extra:
        key = s.lower()[:40]
        if key not in seen:
            seen.add(key)
            uniq.append(s)
    return uniq


def build():
    out, stats = {}, []
    for n in range(1, 65):
        h = HEX[n]
        lb = bits[n]
        pool = pool_for(h)
        used = set()
        out[n] = {}
        for pos in range(1, 7):
            pol = "yang" if lb[pos - 1] == "1" else "yin"
            picks = OPENERS[pos][pol]
            opener = picks[(n * 5 + pos * 3) % len(picks)]
            # содержательная фраза: берём первую ещё не использованную в этой гексаграмме
            body = None
            for shift in range(len(pool)):
                cand = pool[(n + pos * 2 + shift) % len(pool)]
                if cand not in used:
                    body = cand
                    used.add(cand)
                    break
            if body is None:
                body = pool[(n + pos * 2) % len(pool)]
            steps = STEP[pos]
            step = steps[(n + pos) % len(steps)]
            closer = CLOSERS[(n * 3 + pos) % len(CLOSERS)]
            out[n][pos] = " ".join([opener, body, step, closer])
        stats.append((n, len(used)))
    return out, stats


